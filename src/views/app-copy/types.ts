/**
 * app-copy – טיפוסי הנתונים של קולקציית `app-copy` ב-Firestore.
 *
 * מסמך אחד לכל מפתח טקסט באפליקציה (מזהה המסמך = שם המפתח ב-i18n של
 * האפליקציה, למשל `zemanim_sunrise`). האפליקציה מושכת דלתות לפי
 * `timestamp >= watermark`, לכן כל שמירה/פרסום חייבת לעדכן `timestamp`
 * לזמן הנוכחי (מילישניות).
 */

export type AppCopyDoc = {
    /** שם המפתח – זהה למזהה המסמך */
    key: string;
    /** הטקסט בעברית ('' = אין דריסה, האפליקציה תציג את הטקסט המובנה) */
    he: string;
    /** הטקסט באנגלית ('' = אין דריסה) */
    en: string;
    /** קיבוץ לפי מסך/נושא – לתצוגה ב-CMS בלבד */
    category: string;
    /** הסבר לעורך איפה הטקסט מופיע – לתצוגה ב-CMS בלבד */
    description: string;
    /** סדר תצוגה יציב (נקבע בזריעה) – לתצוגה ב-CMS בלבד */
    order: number;
    /** חותמת שינוי במילישניות – מניעה את סנכרון הדלתות באפליקציה */
    timestamp: number;
};

/** ערכי שפה בעריכה (לפני שמירה) */
export type AppCopyEdit = {
    he: string;
    en: string;
};
